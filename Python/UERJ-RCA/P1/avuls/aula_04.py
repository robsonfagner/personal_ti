# Fazer um programa para ler 4 números e imprimir a média.

s1 = float(input("Digite sua primeira nota:"))
s2 = float(input("Digite sua segunda nota:"))
s3 = float(input("Digite sua terceira nota:"))
s4 = float(input("Digite sua quarta nota:"))

media = (s1+s2+s3+s4)/4

print(f"Sua média foi de {media}")